const DICTIONARIES: Record<Lang, Dict> = { fr, en };

/** Translates a key, interpolating {0}, {1}… positional arguments. */
export function translate(lang: Lang, key: string, ...args: (string | number)[]): string {
  const value = DICTIONARIES[lang][key] ?? DICTIONARIES.fr[key] ?? key;
  if (args.length === 0) return value;
  return value.replace(/\{(\d+)\}/g, (match, index) => {
    const arg = args[Number(index)];
    return arg === undefined ? match : String(arg);
  });
}

/** Formats an ISO date in the conventions of the active language. */
export function formatDate(lang: Lang, value: string | Date | null | undefined): string {
  if (!value) return "—";
  const date = typeof value === "string" ? new Date(value) : value;
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(lang === "fr" ? "fr-FR" : "en-GB", {
    day: "2-digit",
    month: lang === "fr" ? "2-digit" : "short",
    year: "numeric",
  }).format(date);
}
